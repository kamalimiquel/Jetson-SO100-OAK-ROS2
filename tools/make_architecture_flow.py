#!/usr/bin/env python3
"""Generate docs/architecture-flow.svg — the cell as it is implemented today.

Regenerate after a change in the stack:

    python3 tools/make_architecture_flow.py && rsvg-convert -o docs/architecture-flow.png docs/architecture-flow.svg

Colour code, same as the README legend: green = implemented and verified on the hardware,
amber = code written but the hardware or the capture is still pending, dashed grey = missing.
"""

from xml.sax.saxutils import escape

W, H = 1660, 1340
BG = "#0b1220"
INK = "#e8edf5"
DIM = "#8892a6"
FRAME = "#263042"
HEAD = "#1a2436"
GREEN_F, GREEN_S, GREEN_T = "#10251a", "#3fb950", "#7ee2a8"
AMBER_F, AMBER_S, AMBER_T = "#2a2113", "#d99036", "#f0b866"
GREY_F, GREY_S, GREY_T = "#171a21", "#6b7280", "#9aa4b2"
BLUE_S = "#4b8bd6"          # generic / DDS over the LAN
USB3 = "#4b8bd6"            # USB 3, 5 Gb/s  — the only link that needs a USB3 cable
USBFS = "#a374e0"           # USB full speed, 12 Mb/s — serial adapter and the wrist webcam
DDS = "#7c8ba1"             # the internal ROS2 spine

out = []


def add(s):
    out.append(s)


def box(x, y, w, h, kind="green", r=8):
    fill, stroke = {"green": (GREEN_F, GREEN_S), "amber": (AMBER_F, AMBER_S),
                    "grey": (GREY_F, GREY_S)}[kind]
    dash = ' stroke-dasharray="7 5"' if kind == "grey" else ""
    add('<rect x="%d" y="%d" width="%d" height="%d" rx="%d" fill="%s" stroke="%s"%s/>'
        % (x, y, w, h, r, fill, stroke, dash))


def text(x, y, s, size=11.5, fill=DIM, bold=False, anchor=None):
    a = ' text-anchor="%s"' % anchor if anchor else ""
    add('<text x="%d" y="%d" fill="%s" font-size="%s"%s%s>%s</text>'
        % (x, y, fill, size, ' font-weight="bold"' if bold else "", a, escape(s)))


def card(x, y, w, h, title, lines, kind="green"):
    box(x, y, w, h, kind)
    colour = {"green": GREEN_T, "amber": AMBER_T, "grey": GREY_T}[kind]
    text(x + 14, y + 24, title, 14, colour, bold=True)
    for i, line in enumerate(lines):
        text(x + 14, y + 42 + i * 15, line, 11)


def arrow(x1, y1, x2, y2, colour=BLUE_S, dash=False):
    d = ' stroke-dasharray="5 4"' if dash else ""
    add('<path d="M %d %d L %d %d" stroke="%s" stroke-width="1.6" fill="none" '
        'marker-end="url(#arw)"%s/>' % (x1, y1, x2, y2, colour, d))


def label(x, y, s, colour=DIM, size=10.5, anchor="middle"):
    add('<text x="%d" y="%d" fill="%s" font-size="%s" text-anchor="%s">%s</text>'
        % (x, y, colour, size, anchor, escape(s)))


add('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" '
    'font-family="DejaVu Sans, sans-serif">' % (W, H))
add('<defs><marker id="arw" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" '
    'markerHeight="6" orient="auto-start-reverse"><path d="M 0 0 L 10 5 L 0 10 z" '
    'fill="%s"/></marker></defs>' % BLUE_S)
add('<rect width="%d" height="%d" fill="%s"/>' % (W, H, BG))

text(36, 44, "Jetson-SO100-OAK-ROS2 — data flow (two-arm configuration, 2026-11-13)", 25, INK, bold=True)
text(36, 68, "ROS2 Humble · FastDDS · domain 42 · one container per job · generated by "
             "tools/make_architecture_flow.py", 13)

for i, (kind, txt) in enumerate([("green", "live / verified"),
                                ("amber", "code done, hardware still pending"),
                                ("grey", "missing")]):
    y = 40 + i * 20
    box(1215, y, 18, 12, kind, r=3)
    text(1239, y + 11, txt, 12)

# link types: the wire tells you the bus, the same colours on the three device arrows
for i, (col, txt) in enumerate([(USB3, "USB 3 · 5 Gb/s"),
                               (USBFS, "USB full speed · 12 Mb/s"),
                               (DDS, "DDS / HTTP over the LAN")]):
    y = 108 + i * 18
    add('<path d="M 1215 %d L 1233 %d" stroke="%s" stroke-width="2.4"/>'
        % (y + 6, y + 6, col))
    text(1241, y + 10, txt, 11.5)

# ----------------------------------------------------------------- frames
frames = [(30, 110, 360, 1150, "DEVICES"),
          (410, 110, 780, 1150, "JETSON XAVIER NX 16 GB — Docker, one container per job"),
          (1210, 110, 420, 1150, "WINDOWS 11 HOME PC — LAN")]
for x, y, w, h, title in frames:
    add('<rect x="%d" y="%d" width="%d" height="%d" fill="none" stroke="%s"/>' % (x, y, w, h, FRAME))
    add('<rect x="%d" y="%d" width="%d" height="34" fill="%s"/>' % (x, y, w, HEAD))
    text(x + 12, y + 23, title, 14, INK, bold=True)

# ----------------------------------------------------------------- devices
card(50, 170, 320, 108, "SO-100 arm 1 + arm 2 — 6 axes each",
     ["Feetech bus over two CH9102 adapters (12 Mb/s), keyed by serial",
      "arm1 5971081400 -> /dev/arm1_tty (+so100_arm) · so100_cell",
      "arm2 5A46085595 -> /dev/arm2_tty · so100_cell_b"], "green")
card(50, 285, 320, 92, "OAK-D POE — scene camera",
     ["colour IMX378 + 2× OV9282, 7.5 cm baseline",
      "USB 3 at 5 Gb/s — needs the USB 3 cable of §3.1"])
card(50, 392, 320, 122, "2× USB RGB webcams — wrist", [
     "one on each moving jaw, 640x480 at 10 Hz (ADR-0022)",
     "UVC, USB full speed (12 Mb/s)",
     "arm1 046d:08aa -> /dev/arm1_wrist · arm2 VF0770 041e:4095 -> /dev/arm2_wrist",
     "focus at 10-15 cm: the §10.5 procedure (per camera)"], "green")

# ----------------------------------------------------------------- containers
card(430, 170, 350, 110, "so100-arm (arm 1) + so100-arm2 (arm 2)", [
    "joint servers :8002/:8003 · torque proxies :8092/:8095",
    "/joint_states and /arm2/joint_states at 50 Hz",
    "TF prefix arm2_ · base->arm2_base static at 0, 0.30, 0"], "green")

card(430, 306, 350, 168, "so100-cams", [
    "oak_cams: colour/left/right (JPEG), depth, confidence,",
    "/oak/scene/points — x,y,z,rgb in the colour frame",
    "oak_stream_views: 5 Hz colourised depth + confidence",
    "wrist_cam ×2: /gripper/image/compressed and",
    "  /arm2/gripper/image/compressed at 10 Hz (Cams tab picks one)",
    "viewers: :8090 stereo+confidence, :8091 cloud"], "green")

card(430, 490, 350, 132, "so100-control", [
    "ik + arm2_ik: /ik/target and /arm2/ik/target (in base / arm2_base) →",
    "/ik/solution, /arm2/ik/solution · /joint_targets if IK_APPLY=1",
    "DLS + geometric Jacobian · 0.0 mm median round trip"], "green")

card(430, 626, 350, 96, "so100-perception", [
    "empty: the grasp pipeline lands here",
    "segmentation → GraspGen request"], "grey")

card(430, 738, 350, 150, "so100-web", [
    "tabs page :80 (six tabs incl. Cams) · ttyd :7681",
    "RViz2 :6080 (on demand) — both arms (arm2_ TF prefix) + colour + 2 cams",
    "rqt_graph :6081",
    "torque proxies :8092/:8095 · power + RViz control :8099"], "green")

card(430, 904, 350, 96, "so100-rosbridge", [
    "rosbridge_websocket at ws://:9090",
    "any LAN client reads the whole cell as JSON"], "green")

# ROS2 bus band
box(430, 1024, 740, 62, "green")
text(444, 1046, "ROS2 bus — FastDDS · domain 42 · network + ipc host", 14, GREEN_T, bold=True)
text(444, 1066, "thirteen nodes standing today — sixteen when RViz is up — discovered from every container ", 11)

# ----------------------------------------------------------------- windows
card(1230, 170, 380, 92, "Browser on the PC", [
    "the seven tabs over HTTP + noVNC (no ROS on Windows)",
    "Cams (Arm 1 / Arm 2) · torque switch · shutdown"], "green")
card(1230, 285, 380, 92, "MuJoCo twin", [
    "roslibpy → ws://<xavier>:9090",
    "mirrors /joint_states + /arm2/joint_states (two arms, 0.30 m)"], "green")
card(1230, 400, 380, 92, "F710 teleop — Python client", [
    "roslibpy → ws://<xavier>:9090 · no ROS on Windows",
    "joint-step + cartesian-feel · hold A 5 s switches arms · torque per arm"], "green")
card(1230, 515, 380, 92, "GraspGen", [
    "runs here, served over HTTP",
    "needs the grasp pipeline and the IK node"], "grey")
card(1230, 630, 380, 92, "Policy training (MuJoCo)", [
    "needs episode recording + LeRobot export"], "grey")

# ----------------------------------------------------------------- arrows
# one spine on the right of the Jetson column: every container ties into the ROS2 bus there,
# instead of six long lines crossing the picture
SPINE = 1120
add('<path d="M %d 1055 L %d 216" stroke="%s" stroke-width="2" fill="none"/>' % (SPINE, SPINE, DDS))
for y in (230, 390, 550, 674, 813, 952):          # arm, cams, control, perception, web, rosbridge
    add('<path d="M 780 %d L %d %d" stroke="%s" stroke-width="1.4" fill="none"/>'
        % (y, SPINE, y, DDS))

# device → container, coloured and labelled by the bus it actually runs on (lsusb -t,
# 2026-11-11): the OAK negotiates 5000M, while the arm's serial adapter and the wrist webcam
# both sit on a 12M hub — they are USB full-speed devices, not USB 2 High Speed.
arrow(370, 216, 430, 216, USBFS)
label(400, 210, "12 Mb/s", USBFS, 9.5)
arrow(370, 331, 430, 331, USB3)
label(400, 325, "5 Gb/s", USB3, 9.5)
arrow(370, 453, 430, 392, USBFS)
label(404, 424, "12 Mb/s", USBFS, 9.5)

arrow(SPINE, 1055, SPINE, 1030, DDS)               # spine → bus band
arrow(SPINE, 600, 1205, 600, DDS)                  # the cell over the LAN
label(1163, 590, "LAN", DIM, 10)
label(1163, 618, ":9090 · :80", DIM, 9.5)

# perception → GraspGen, routed along the bottom so it does not cross the LAN link
add('<path d="M 605 722 L 605 1244 L 1420 1244 L 1420 716" fill="none" stroke="%s" '
    'stroke-width="1.6" stroke-dasharray="5 4" marker-end="url(#arw)"/>' % GREY_S)
label(1000, 1236, "HTTP — the grasp request (to be written)", GREY_T, 10)

# ----------------------------------------------------------------- bottom band
add('<rect x="30" y="1286" width="1600" height="34" rx="6" fill="#101725" stroke="%s"/>' % FRAME)
text(44, 1308, "Left to build:  arm 2 calibration (so100_cell_b) to bring the two-arm cell live · "
               "grasp pipeline (GraspGen client) · episode recording + LeRobot export · hand-eye "
               "extrinsic · wrist camera focus measurement per camera", 12, DIM)

add("</svg>")
open("docs/architecture-flow.svg", "w").write("\n".join(out) + "\n")
print("wrote docs/architecture-flow.svg (%d elements)" % len(out))
