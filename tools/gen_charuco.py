#!/usr/bin/env python3
"""Generate the hand-eye ChArUco board at TRUE physical size (PNG + A4 PDF).

The board is the one every capture and every solve in this cell assumes:

    cv2.aruco.CharucoBoard((5, 5), 0.018, 0.0135, DICT_4X4_50)

i.e. **18.0 mm squares, 13.5 mm markers, 5x5**. That number is what
`handeye_grab.py` / `handeye_capture.py` store in `poses.json` and what
`handeye_bundle.py` puts into the object points, so a print whose squares are not
18.0 mm silently poisons the whole calibration: the board is then either nearer or
farther than the solver believes, and the error shows up as the board "moving"
relative to the jaw between shots.

This script exists because the board was never generated by a script in this repo:
`docs/charuco-board.pdf` was a one-off, and a PDF is only a claim about size. `--check`
re-renders it at a known DPI and measures the printed squares, so the claim is tested:

    check: inner-corner span 54.06 x 54.06 mm (want 54.0 x 54.0)
    check: -> squares of 18.02 mm (want 18.0)

(16 inner corners of a 5x5 board span 3 squares, not 4: 3 x 18 = 54 mm.)

    uv run --with "opencv-contrib-python-headless<5" --with numpy \
        python tools/gen_charuco.py --out docs/charuco-board

writes `docs/charuco-board.png` (exact pixels, 24 px/mm) and
`docs/charuco-board.pdf` (A4, the board printed at a 100 mm side). `--check`
re-renders the PDF with pdftoppm and measures the printed squares.

Printing: 100 % / "actual size", never "fit to page", on a printer that is not
scaling; then measure one square with a caliper. Then pass that measured number to
the capture scripts (`--square-mm`), which is what the solver will believe.
"""

import argparse
import os
import shutil
import subprocess
import sys
import zlib

import cv2
import numpy as np

SQUARES = 5
SQUARE_M = 0.018
MARKER_M = 0.0135
DICT = cv2.aruco.DICT_4X4_50

PX_PER_MM = 24                     # 609.6 dpi — integer px per mm, so 18 mm = 432 px exactly
BOARD_SIDE_MM = SQUARES * SQUARE_M * 1000.0        # 90.0
PRINT_SIDE_MM = 100.0              # the printed patch: board 90 mm + a 5 mm quiet zone each side
PT_PER_MM = 72.0 / 25.4


def draw_board():
    """The 100 mm patch as a grayscale image: board + quiet zone + caption strip."""
    board = cv2.aruco.CharucoBoard((SQUARES, SQUARES), SQUARE_M, MARKER_M,
                                   cv2.aruco.getPredefinedDictionary(DICT))
    side = int(round(BOARD_SIDE_MM * PX_PER_MM))            # 2160 px = 90 mm
    img = board.generateImage((side, side), marginSize=0, borderBits=1)
    # generateImage is trusted only after measuring itself: one square must be side/SQUARES
    row = np.where((img < 128).any(axis=1))[0].min() + 5
    run = np.concatenate(([0], (img[row] < 128).astype(np.int8), [0]))   # pad: the row may start black
    starts = np.where(np.diff(run) == 1)[0]
    ends = np.where(np.diff(run) == -1)[0]
    widths = [int(b - a) for a, b in zip(starts, ends)]
    want = side / float(SQUARES)
    if not widths or abs(widths[0] - want) > 2:
        raise SystemExit("gen_charuco: generateImage drew %s px black squares, wanted %.1f — this "
                         "OpenCV version sizes the board differently, fix the generator"
                         % (widths[:3], want))
    margin = int(round((PRINT_SIDE_MM - BOARD_SIDE_MM) / 2.0 * PX_PER_MM))   # 120 px = 5 mm
    patch = cv2.copyMakeBorder(img, margin, margin, margin, margin,
                               cv2.BORDER_CONSTANT, value=255)

    # caption strip, same scale (24 px/mm), printed under the board
    strip_h = int(round(22.0 * PX_PER_MM))
    strip = np.full((strip_h, patch.shape[1]), 255, np.uint8)
    lines = [
        "SO-101 hand-eye board - ChArUco 5x5 - 18.0 mm squares - 13.5 mm markers - DICT_4X4_50",
        "Printed at a 100 mm side. Measure a square: it must read 18.0 mm. Print 100%%, never 'fit to page'.",
    ]
    for i, txt in enumerate(lines):
        cv2.putText(strip, txt, (int(2.0 * PX_PER_MM), int((7.0 + 6.0 * i) * PX_PER_MM)),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.85, 0, 2, cv2.LINE_AA)
    # a 100 mm ruler with ticks every 10 mm: a caliper-free scale check
    y0 = int(19.0 * PX_PER_MM)
    x0 = int(2.0 * PX_PER_MM)
    cv2.line(strip, (x0, y0), (x0 + int(100 * PX_PER_MM), y0), 0, 2)
    for mm in range(0, 101, 10):
        x = x0 + int(mm * PX_PER_MM)
        h = 3 if mm % 50 == 0 else 2
        cv2.line(strip, (x, y0), (x, y0 - int(h * PX_PER_MM * 0.35)), 0, 2)
        if mm % 20 == 0:
            cv2.putText(strip, str(mm), (x - 12, y0 + int(2.6 * PX_PER_MM)),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.5, 0, 1, cv2.LINE_AA)
    return np.vstack([patch, strip])


def write_pdf(png_bytes_path, pdf_path, w_mm, h_mm):
    """Minimal vector-free PDF: one grayscale image, placed at an exact physical size."""
    img = cv2.imread(png_bytes_path, cv2.IMREAD_GRAYSCALE)
    h, w = img.shape
    raw = zlib.compress(img.tobytes())
    pw, ph = 595.276, 841.89                                  # A4 in points
    dw, dh = w_mm * PT_PER_MM, h_mm * PT_PER_MM
    x, y = (pw - dw) / 2.0, (ph - dh) / 2.0
    content = ("q %.4f 0 0 %.4f %.4f %.4f cm /Im0 Do Q\n" % (dw, dh, x, y)).encode()

    objs = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        ("<< /Type /Page /Parent 2 0 R /MediaBox [0 0 %.3f %.3f] "
         "/Resources << /XObject << /Im0 5 0 R >> >> /Contents 4 0 R >>" % (pw, ph)).encode(),
        b"<< /Length %d >>\nstream\n%s\nendstream" % (len(content), content),
        ("<< /Type /XObject /Subtype /Image /Width %d /Height %d /ColorSpace /DeviceGray "
         "/BitsPerComponent 8 /Filter /FlateDecode /Length %d >>\nstream\n" % (w, h, len(raw))
         ).encode() + raw + b"\nendstream",
    ]
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for i, body in enumerate(objs, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % i + body + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1)
    for off in offsets:
        out += b"%010d 00000 n \n" % off
    out += (b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n"
            % (len(objs) + 1, xref))
    with open(pdf_path, "wb") as fh:
        fh.write(bytes(out))


def check(pdf_path):
    """Render the PDF at a known DPI and measure the printed squares. No printer, no trust."""
    if not shutil.which("pdftoppm"):
        print("check: pdftoppm not installed (poppler) — cannot verify the print scale")
        return 1
    tmp = os.path.join(os.path.dirname(os.path.abspath(pdf_path)), ".charuco-check")
    os.makedirs(tmp, exist_ok=True)
    dpi = 300
    subprocess.run(["pdftoppm", "-r", str(dpi), "-png", pdf_path,
                    os.path.join(tmp, "page")], check=True)
    page = sorted(f for f in os.listdir(tmp) if f.endswith(".png"))[0]
    img = cv2.imread(os.path.join(tmp, page), cv2.IMREAD_GRAYSCALE)
    board = cv2.aruco.CharucoBoard((SQUARES, SQUARES), SQUARE_M, MARKER_M,
                                   cv2.aruco.getPredefinedDictionary(DICT))
    corners, _, _, _ = cv2.aruco.CharucoDetector(board).detectBoard(img)
    if corners is None or len(corners) < 16:
        print("check: board not detected in the rendered page — the PDF is broken")
        return 1
    c = corners.reshape(-1, 2)
    span_px = c.max(axis=0) - c.min(axis=0)
    mm = span_px * 25.4 / dpi
    # 16 inner corners of a 5x5 board span SQUARES-2 squares (3 x 18 = 54 mm), not 4.
    want = (SQUARES - 2) * SQUARE_M * 1000.0
    print("check: inner-corner span %.2f x %.2f mm (want %.1f x %.1f)" % (mm[0], mm[1], want, want))
    print("check: -> squares of %.2f mm (want %.1f)" % (mm[0] / (SQUARES - 2), SQUARE_M * 1000.0))
    ok = abs(mm[0] - want) <= 1.0 and abs(mm[1] - want) <= 1.0
    print("check: %s" % ("OK — print this at 100% and measure one square" if ok
                         else "FAILED — the PDF is not at true scale"))
    shutil.rmtree(tmp, ignore_errors=True)
    return 0 if ok else 1


def main():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(here, "docs", "charuco-board"),
                    help="output basename; .png and .pdf are written next to it")
    ap.add_argument("--check", action="store_true",
                    help="re-render the PDF and measure the printed squares")
    args = ap.parse_args()

    if args.check:
        return check(args.out + ".pdf")

    patch = draw_board()
    png, pdf = args.out + ".png", args.out + ".pdf"
    os.makedirs(os.path.dirname(os.path.abspath(png)), exist_ok=True)
    cv2.imwrite(png, patch)
    h_mm = patch.shape[0] / float(PX_PER_MM)
    write_pdf(png, pdf, PRINT_SIDE_MM, h_mm)
    print("wrote %s (%dx%d px, %.1f x %.1f mm at %d px/mm)"
          % (png, patch.shape[1], patch.shape[0], PRINT_SIDE_MM, h_mm, PX_PER_MM))
    print("wrote %s (A4, board at a %.0f mm side: %.0f mm squares)"
          % (pdf, PRINT_SIDE_MM, BOARD_SIDE_MM))
    print("now run:  python tools/gen_charuco.py --out %s --check" % args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
